"""Génère version_info.txt (Propriétés > Détails de FastVer.exe) à partir de APP_VERSION et BUILD de fastver.py.
Generates version_info.txt (FastVer.exe Properties > Details) from fastver.py's APP_VERSION and BUILD."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "fastver.py"), encoding="utf-8").read()
version = re.search(r'^APP_VERSION = "([^"]+)"', src, re.M).group(1)
build = re.search(r'^BUILD = "([^"]+)"', src, re.M).group(1)
nums = [int(n) for n in re.findall(r"\d+", version)[:4]]
nums += [0] * (4 - len(nums))
t = tuple(nums)

text = f"""# Fichier généré par tools/make_version_info.py : ne pas modifier à la main.
# Generated by tools/make_version_info.py: don't edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={t}, prodvers={t}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040C04B0', [
      StringStruct('CompanyName', 'Bulls64'),
      StringStruct('FileDescription', 'FastVer — À propos de Fastfetch'),
      StringStruct('FileVersion', '{version} (build {build})'),
      StringStruct('InternalName', 'FastVer'),
      StringStruct('LegalCopyright', '© 2026 Bulls64'),
      StringStruct('OriginalFilename', 'FastVer.exe'),
      StringStruct('ProductName', 'FastVer'),
      StringStruct('ProductVersion', '{version}')])]),
    VarFileInfo([VarStruct('Translation', [0x040C, 1200])])
  ]
)
"""
open(os.path.join(ROOT, "version_info.txt"), "w", encoding="utf-8").write(text)
print(f"version_info.txt : FastVer {version} (build {build})")
